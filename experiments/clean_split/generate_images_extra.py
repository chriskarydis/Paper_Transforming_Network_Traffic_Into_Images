#!/usr/bin/env python3
"""Generates the two additional encodings needed for Meta-LightGBM under the
unified split: Packet_RGB and Flow_Greyscale (Packet_Greyscale and Flow_RGB
were already generated by generate_images.py)."""
import csv
import subprocess
import time
from pathlib import Path

BASE = Path.home() / "thesis_heifip"
HEIFIP = BASE / "tools" / "heiFIP" / "heiFIP" / "build" / "heiFIP"
MANIFEST = Path(__file__).parent / "manifest.csv"
OUT_PACKET_RGB = Path(__file__).parent / "images_packet_rgb"
OUT_FLOW_GREY = Path(__file__).parent / "images_flow_grey"
TIMEOUT = 30

def main():
    rows = list(csv.DictReader(open(MANIFEST)))
    print(f"Total flows to process: {len(rows)}")

    t0 = time.time()
    errors = 0

    for i, r in enumerate(rows):
        pcap = Path(r["pcap"])
        cls = r["class"]
        split = r["split"]
        stem = pcap.stem

        pkt_dir = OUT_PACKET_RGB / split / cls
        flow_dir = OUT_FLOW_GREY / split / cls
        pkt_dir.mkdir(parents=True, exist_ok=True)
        flow_dir.mkdir(parents=True, exist_ok=True)

        try:
            subprocess.run(
                [str(HEIFIP), "-i", str(pcap), "-o", str(pkt_dir),
                 "-m", "PacketImage", "--rgb", "--min-pkts", "1", "--name", stem],
                capture_output=True, timeout=TIMEOUT)
            subprocess.run(
                [str(HEIFIP), "-i", str(pcap), "-o", str(flow_dir),
                 "-m", "FlowImage", "--min-pkts", "1", "--name", stem],
                capture_output=True, timeout=TIMEOUT)
        except subprocess.TimeoutExpired:
            errors += 1
            continue

        if (i + 1) % 250 == 0:
            elapsed = time.time() - t0
            eta = elapsed / (i + 1) * (len(rows) - i - 1)
            print(f"  [{i+1}/{len(rows)}] elapsed={elapsed/60:.1f}min  ETA={eta/60:.1f}min  errors={errors}")

    n_pkt_imgs = sum(1 for _ in OUT_PACKET_RGB.rglob("*.png"))
    n_flow_imgs = sum(1 for _ in OUT_FLOW_GREY.rglob("*.png"))
    print(f"\nDone in {(time.time()-t0)/60:.1f} min")
    print(f"Packet RGB images: {n_pkt_imgs}")
    print(f"Flow Greyscale images: {n_flow_imgs}")
    print(f"Errors/timeouts: {errors}")

if __name__ == "__main__":
    main()
